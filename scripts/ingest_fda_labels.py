"""Add the full official FDA label text to GLPal's trusted library (optional).

Downloads the current prescribing information for Wegovy, Ozempic, Mounjaro and Zepbound from
the public openFDA drug label API and saves it as knowledge/fda_labels.json, split into
section-sized passages that the coach can search and cite. Re-run it whenever labels change.

    python scripts/ingest_fda_labels.py
"""
import json
import re
import sys
from pathlib import Path

import httpx

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "knowledge" / "fda_labels.json"
DRUGS = {"WEGOVY": ["wegovy", "semaglutide"], "OZEMPIC": ["ozempic", "semaglutide"],
         "MOUNJARO": ["mounjaro", "tirzepatide"], "ZEPBOUND": ["zepbound", "tirzepatide"]}
SECTIONS = {
    "boxed_warning": "Boxed warning", "indications_and_usage": "Indications and usage",
    "dosage_and_administration": "Dosage and administration", "contraindications": "Contraindications",
    "warnings_and_cautions": "Warnings and precautions", "adverse_reactions": "Adverse reactions",
    "drug_interactions": "Drug interactions", "use_in_specific_populations": "Use in specific populations",
    "storage_and_handling": "How supplied and storage", "information_for_patients": "Patient counseling information",
}
CHUNK = 900   # characters per passage


def chunks(text: str):
    sentences = re.split(r"(?<=[.!?])\s+", re.sub(r"\s+", " ", text).strip())
    buf = ""
    for s in sentences:
        if len(buf) + len(s) > CHUNK and buf:
            yield buf.strip()
            buf = ""
        buf += s + " "
    if buf.strip():
        yield buf.strip()


def main() -> int:
    sources, cards = {}, []
    for brand, tags in DRUGS.items():
        url = f'https://api.fda.gov/drug/label.json?search=openfda.brand_name:"{brand}"&limit=1'
        try:
            r = httpx.get(url, timeout=30)
            r.raise_for_status()
            label = r.json()["results"][0]
        except Exception as e:  # noqa: BLE001
            print(f"  {brand}: could not download ({type(e).__name__}); skipped")
            continue
        set_id = label.get("set_id", "")
        key = f"fda_{brand.lower()}"
        sources[key] = {"name": f"{brand.title()} prescribing information (FDA label via openFDA, "
                                f"effective {label.get('effective_time', 'n/a')})",
                        "url": f"https://dailymed.nlm.nih.gov/dailymed/drugInfo.cfm?setid={set_id}" if set_id else url}
        n = 0
        for field, section in SECTIONS.items():
            for text in label.get(field, []):
                for i, part in enumerate(chunks(text)):
                    cards.append({"id": f"{brand.lower()}-{field}-{n}", "source": key, "section": section,
                                  "drugs": tags, "title": f"{brand.title()}: {section}" + (f" (part {i + 1})" if i else ""),
                                  "text": part})
                    n += 1
        print(f"  {brand}: {n} passages")
    if not cards:
        print("Nothing downloaded; library unchanged.")
        return 1
    OUT.write_text(json.dumps({"_about": "Generated by scripts/ingest_fda_labels.py from openFDA.",
                               "sources": sources, "cards": cards}, indent=1), encoding="utf-8")
    print(f"Saved {len(cards)} passages to {OUT.relative_to(ROOT)}. Restart GLPal to use them.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
